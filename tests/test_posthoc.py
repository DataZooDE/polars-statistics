PTUKEY_SHA256 = "44e0ba0d0e97b0d399082cd7dec6f799176548dc79e562e7681edddb5c6e8ef2"

QTUKEY_PATH = FIXTURES / "qtukey_reference.csv"
QTUKEY_SHA256 = "b36dc2a1a06f0d3add5af29b09fe48d32392a380e49c3aea644161a2d86590eb"

POSTHOC_DATA_PATH = FIXTURES / "posthoc_data.csv"
POSTHOC_DATA_SHA256 = "f821db9354be652a5b7c13455ccd0cd89d172aab731bc48395f0c48130b5fbff"

POSTHOC_REFERENCE_PATH = FIXTURES / "posthoc_reference.csv"
POSTHOC_REFERENCE_SHA256 = "39f12d7d61d1489ebb4fe63f43182ab97315da5ccc3626455bc06e9447a7cdec"


def _close(a, b, tol: float) -> bool:
    """Upstream comparison rule: |a - b| <= tol * (1 + |b|); NaN == NaN."""
    if a is None or b is None:
        return a is None and b is None
    if math.isnan(a) and math.isnan(b):
        return True
    if math.isnan(a) or math.isnan(b):
        return False
    return abs(a - b) <= tol * (1 + abs(b))


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_csv(path: Path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


_PTUKEY_ROWS = _load_csv(PTUKEY_PATH)
_QTUKEY_ROWS = _load_csv(QTUKEY_PATH)
_POSTHOC_DATA_ROWS = _load_csv(POSTHOC_DATA_PATH)
_POSTHOC_REFERENCE_ROWS = _load_csv(POSTHOC_REFERENCE_PATH)

# set -> (values, groups), parsed from posthoc_data.csv's space-separated columns.
_POSTHOC_SETS = {
    r["set"]: (
        [float(v) for v in r["x"].split()],
        r["g"].split(),
    )
    for r in _POSTHOC_DATA_ROWS
}

# (set, test, pooled, alternative, option) -> [reference rows], preserving
# upstream row order (R's TukeyHSD row order: B-A, C-A, C-B, ...).
_POSTHOC_COMBOS: dict = defaultdict(list)
for _r in _POSTHOC_REFERENCE_ROWS:
    _key = (_r["set"], _r["test"], _r["pooled"], _r["alternative"], _r["option"])
    _POSTHOC_COMBOS[_key].append(_r)


def _combo_id(key) -> str:
    set_, test, pooled, alternative, option = key
    return f"set{set_}-{test}-{pooled}-{alternative}-{option}"


def _run_pairwise(test: str, values: list, groups: list, pooled: str, alternative: str, option: str):
    """Build the (x, g) frame and call the matching ps.* pairwise builder."""
    df = pl.DataFrame({"x": values, "g": groups})
    if test == "tukey":
        expr = ps.tukey_hsd("x", "g", conf_level=float(option))
    elif test == "pairwise_t":
        expr = ps.pairwise_t_test(
            "x",
            "g",
            pooled_sd=(pooled == "TRUE"),
            p_adjust_method=option,
            alternative=alternative,
        )
    else:
        expr = ps.dunn_test("x", "g", p_adjust_method=option)

    out = df.select(expr.alias("ph")).explode("ph").unnest("ph")
    return {
        (row["group1"], row["group2"]): row
        for row in out.to_dicts()
        if row["group1"] is not None
    }


def test_ptukey_matches_r():
    """ps.ptukey matches R's ptukey on all 630 upstream rows, both tails."""
    df = pl.DataFrame(
        {
            "q": [float(r["q"]) for r in _PTUKEY_ROWS],
            "nmeans": [float(r["nmeans"]) for r in _PTUKEY_ROWS],
            "df": [float(r["df"]) for r in _PTUKEY_ROWS],
            "nranges": [float(r["nranges"]) for r in _PTUKEY_ROWS],
        }
    )
    lower_ref = [float(r["lower"]) for r in _PTUKEY_ROWS]
    upper_ref = [float(r["upper"]) for r in _PTUKEY_ROWS]

    lower_got = df.select(ps.ptukey("q", "nmeans", "df", "nranges"))["q"].to_list()
    upper_got = df.select(
        ps.ptukey("q", "nmeans", "df", "nranges", lower_tail=False)
    )["q"].to_list()

    for i, (g, w) in enumerate(zip(lower_got, lower_ref)):
        assert abs(g - w) < 1e-10, f"lower row {i}: got={g} want={w}"
    for i, (g, w) in enumerate(zip(upper_got, upper_ref)):
        assert abs(g - w) < 1e-10, f"upper row {i}: got={g} want={w}"


def test_qtukey_matches_r():
    """ps.qtukey matches R's qtukey on all 420 upstream rows.

    The upper-tail form `qtukey(1 - p, lower_tail=False)` is within 1e-6 of
    the lower-tail result.
    """
    df = pl.DataFrame(
        {
            "p": [float(r["p"]) for r in _QTUKEY_ROWS],
            "nmeans": [float(r["nmeans"]) for r in _QTUKEY_ROWS],
            "df": [float(r["df"]) for r in _QTUKEY_ROWS],
            "nranges": [float(r["nranges"]) for r in _QTUKEY_ROWS],
        }
    )
    q_ref = [float(r["q"]) for r in _QTUKEY_ROWS]

    q_got = df.select(ps.qtukey("p", "nmeans", "df", "nranges"))["p"].to_list()
    for i, (g, w) in enumerate(zip(q_got, q_ref)):
        assert _close(g, w, 1e-8), f"row {i}: got={g} want={w}"

    q_upper = df.select(
        ps.qtukey(
            1 - pl.col("p"), "nmeans", "df", "nranges", lower_tail=False
        ).alias("q_upper")
    )["q_upper"].to_list()
    for i, (lower, upper) in enumerate(zip(q_got, q_upper)):
        assert _close(lower, upper, 1e-6), f"row {i}: lower={lower} upper={upper}"


def test_tukey_dist_broadcast():
    """Scalar arguments broadcast against columns; length-1 frames round-trip."""
    df = pl.DataFrame({"q": [1.0, 2.0, 3.0, 4.0]})

    a = df.select(ps.ptukey("q", 3, 10))["q"].to_list()
    b = df.select(
        ps.ptukey("q", pl.lit(3.0), pl.lit(10.0), 1.0)
    )["q"].to_list()
    assert a == b

    one_row = pl.DataFrame({"q": [3.5]}).select(ps.ptukey("q", 3, 10))["q"][0]
    # A one-row frame is exactly the scalar computation via a length-1 column.
    direct = pl.DataFrame({"q": [3.5]}).select(ps.ptukey("q", 3.0, 10.0, 1.0))["q"][0]
    assert one_row == direct


def test_tukey_dist_round_trip():
    """For qtukey rows with nranges == 1, ptukey(qtukey(p)) is within 1e-6 of p.

    qtukey's Newton-Raphson solver converges p to its own EPS = 1e-4
    criterion (anofox-statistics-rs `src/posthoc/tukey_dist.rs`); composing
    it with ptukey inherits that solver's convergence slack, so the round
    trip is checked at 1e-6 (the same tolerance the plan's own
    lower-vs-upper-tail round trip above uses), not at ptukey/qtukey's
    individual 1e-10/1e-8 R-reference tolerances. The observed max
    discrepancy across all 210 nranges==1 rows is ~8.6e-8.
    """
    # A handful of upstream reference rows have q == "NaN" themselves (R's own
    # qtukey did not converge for that nmeans/df/p combination, e.g. nmeans=20,
    # df=30, p=0.1); the round trip is meaningless there and is skipped.
    rows = [
        r for r in _QTUKEY_ROWS if r["nranges"] == "1" and r["q"].lower() != "nan"
    ]
    df = pl.DataFrame(
        {
            "p": [float(r["p"]) for r in rows],
            "nmeans": [float(r["nmeans"]) for r in rows],
            "df": [float(r["df"]) for r in rows],
        }
    )
    roundtrip = df.select(
        ps.ptukey(
            ps.qtukey("p", "nmeans", "df", nranges=1), "nmeans", "df", nranges=1
        ).alias("p2")
    )["p2"].to_list()
    for i, (orig, back) in enumerate(zip(df["p"].to_list(), roundtrip)):
        assert abs(orig - back) < 1e-6, f"row {i}: p={orig} roundtrip={back}"


def test_tukey_dist_invalid_params():
    """Invalid parameters give NaN without an exception; a null q gives null."""
    df = pl.DataFrame(
        {
            "q": [1.0, 1.0, 1.0, float("nan"), None],
            "nmeans": [3.0, 1.0, 3.0, 3.0, 3.0],
            "df": [1.0, 10.0, 10.0, 10.0, 10.0],
            "nranges": [1.0, 1.0, 0.0, 1.0, 1.0],
        },
        schema={"q": pl.Float64, "nmeans": pl.Float64, "df": pl.Float64, "nranges": pl.Float64},
    )
    out = df.select(ps.ptukey("q", "nmeans", "df", "nranges"))["q"].to_list()
    assert math.isnan(out[0]), "df < 2 should give NaN"
    assert math.isnan(out[1]), "nmeans < 2 should give NaN"
    assert math.isnan(out[2]), "nranges < 1 should give NaN"
    assert math.isnan(out[3]), "NaN q should give NaN"
    assert out[4] is None, "null q should give null"


