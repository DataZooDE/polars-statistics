"""R-reference tests for `ps.eb_shrink` (anofox-regression 0.5.17's
`solvers::eb_shrink`, issue #58).

Reference values copied verbatim from the upstream crate's own
`tests/r_validation_eb_shrink.rs` (anofox-regression 0.5.22), generated by
`tests/r_scripts/generate_eb_shrink_validation.R` against `metafor` 4.x
(`metafor::rma(yi, sei = se, method = "DL")` / `blup()`). Tolerance matches
the upstream test: `|a - b| <= 1e-10 * max(|b|, 1)`.
"""

