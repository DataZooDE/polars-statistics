def test_none_method_matches_metafor():
    out = (
        pl.DataFrame({"yi": YI, "sei": SEI})
        .select(ps.eb_shrink("yi", "sei", method="none").alias("eb"))
        .unnest("eb")
    )
    assert all(_close(v, NONE_MU) for v in out["mu"].to_list())
    assert all(_close(v, NONE_MU_SE) for v in out["mu_se"].to_list())
    assert out["tau_squared"].to_list() == [0.0] * 5
    assert all(_close(v, DL_Q) for v in out["q"].to_list())
    assert all(_close(v, DL_I2) for v in out["i_squared"].to_list())
    for mu, shrunken in zip(out["mu"].to_list(), out["shrunken"].to_list()):
        assert shrunken == mu


