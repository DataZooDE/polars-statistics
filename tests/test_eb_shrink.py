def _close(a: float, b: float) -> bool:
    """Upstream tolerance rule: |a - b| <= TOL * max(|b|, 1)."""
    if math.isnan(a) and math.isnan(b):
        return True
    if math.isnan(a) or math.isnan(b):
        return False
    return abs(a - b) <= TOL * max(abs(b), 1.0)


def _close_all(got: list, want: list) -> bool:
    return len(got) == len(want) and all(_close(g, w) for g, w in zip(got, want))


def _frames_close(got: pl.DataFrame, want: pl.DataFrame) -> bool:
    """Compare two eb_shrink output frames column-by-column, NaN-aware for the
    float columns and exact for n_groups."""
    if got.height != want.height or set(got.columns) != set(want.columns):
        return False
    for col in want.columns:
        g = got[col].to_list()
        w = want[col].to_list()
        if col == "n_groups":
            if g != w:
                return False
        elif not _close_all(g, w):
            return False
    return True


def test_dl_matches_metafor():
    df = pl.DataFrame({"yi": YI, "sei": SEI})
    out = df.select(ps.eb_shrink("yi", "sei").alias("eb")).unnest("eb")

    assert out.height == 5
    assert all(_close(v, DL_MU) for v in out["mu"].to_list())
    assert all(_close(v, DL_MU_SE) for v in out["mu_se"].to_list())
    assert all(_close(v, DL_TAU2) for v in out["tau_squared"].to_list())
    assert all(_close(v, DL_Q) for v in out["q"].to_list())
    assert all(_close(v, DL_I2) for v in out["i_squared"].to_list())
    assert out["n_groups"].to_list() == [5] * 5

    assert _close_all(out["shrunken"].to_list(), DL_SHRUNKEN)
    assert _close_all(out["weight"].to_list(), DL_WEIGHT)
    assert _close_all(out["shrunken_se"].to_list(), DL_SHRUNKEN_SE)


def test_schema():
    df = pl.DataFrame({"yi": YI, "sei": SEI})
    out = df.select(ps.eb_shrink("yi", "sei").alias("eb")).unnest("eb")

    expected_fields = [
        "shrunken",
        "shrunken_se",
        "weight",
        "mu",
        "mu_se",
        "tau_squared",
        "i_squared",
        "q",
        "n_groups",
    ]
    assert out.columns == expected_fields
    assert out.schema["n_groups"] == pl.UInt32
    for f in expected_fields:
        if f != "n_groups":
            assert out.schema[f] == pl.Float64


def test_build_errors():
    df = pl.DataFrame({"yi": YI, "sei": SEI})

    with pytest.raises(ValueError):
        df.select(ps.eb_shrink("yi", "sei", method="unknown"))

    with pytest.raises(ValueError):
        df.select(ps.eb_shrink("yi", "sei", tau_squared=-0.1))

    with pytest.raises(ValueError):
        df.select(ps.eb_shrink("yi", "sei", tau_squared=float("nan")))


