def test_unusable_rows_stay_aligned():
    baseline = (
        pl.DataFrame({"yi": YI, "sei": SEI})
        .select(ps.eb_shrink("yi", "sei").alias("eb"))
        .unnest("eb")
    )

    variants = [
        (YI + [None], SEI + [0.3]),  # appended row: estimate null
        (YI + [0.5], SEI + [0.0]),  # appended row: std_error 0.0 (non-positive)
        (YI + [float("inf")], SEI + [0.3]),  # appended row: estimate infinite
    ]
    for est, se in variants:
        out = (
            pl.DataFrame({"yi": est, "sei": se})
            .select(ps.eb_shrink("yi", "sei").alias("eb"))
            .unnest("eb")
        )
        assert out.height == 6
        assert _frames_close(out.slice(0, 5), baseline)
        appended = out.row(5, named=True)
        assert math.isnan(appended["shrunken"])
        assert math.isnan(appended["shrunken_se"])
        assert math.isnan(appended["weight"])
        assert out["n_groups"].to_list() == [5] * 6


def test_degenerate_inputs():
    # A single usable row: insufficient data, degrades to NaN, never raises.
    out = (
        pl.DataFrame({"yi": [0.5], "sei": [0.2]})
        .select(ps.eb_shrink("yi", "sei").alias("eb"))
        .unnest("eb")
    )
    assert out.height == 1
    assert math.isnan(out["shrunken"][0])
    assert out["n_groups"][0] == 0

    # Every row unusable (zero, negative, or NaN std_error).
    out = (
        pl.DataFrame({"yi": [0.1, 0.2, 0.3], "sei": [0.0, -1.0, float("nan")]})
        .select(ps.eb_shrink("yi", "sei").alias("eb"))
        .unnest("eb")
    )
    assert out.height == 3
    assert all(math.isnan(v) for v in out["shrunken"].to_list())
    assert out["n_groups"].to_list() == [0, 0, 0]

    # Empty frame: an empty result, never an exception.
    out = (
        pl.DataFrame(schema={"yi": pl.Float64, "sei": pl.Float64})
        .select(ps.eb_shrink("yi", "sei").alias("eb"))
        .unnest("eb")
    )
    assert out.height == 0


def test_over_and_group_by():
    fam_a = pl.DataFrame({"family": ["a"] * 5, "yi": YI, "sei": SEI})
    fam_b_yi = [y + 1.0 for y in YI]
    fam_b = pl.DataFrame({"family": ["b"] * 5, "yi": fam_b_yi, "sei": SEI})
    stacked = pl.concat([fam_a, fam_b])

    separate_a = fam_a.select(ps.eb_shrink("yi", "sei").alias("eb")).unnest("eb")
    separate_b = fam_b.select(ps.eb_shrink("yi", "sei").alias("eb")).unnest("eb")

    over_out = stacked.select(
        pl.col("family"),
        ps.eb_shrink("yi", "sei").over("family").alias("eb"),
    ).unnest("eb")
    got_a = over_out.filter(pl.col("family") == "a").drop("family")
    got_b = over_out.filter(pl.col("family") == "b").drop("family")
    assert _frames_close(got_a, separate_a)
    assert _frames_close(got_b, separate_b)

    grouped = stacked.group_by("family", maintain_order=True).agg(
        ps.eb_shrink("yi", "sei").alias("eb")
    )
    for row in grouped.iter_rows(named=True):
        ref = separate_a if row["family"] == "a" else separate_b
        structs = row["eb"]
        assert len(structs) == 5
        for i, s in enumerate(structs):
            for col in ref.columns:
                if col == "n_groups":
                    assert s[col] == ref[col][i]
                else:
                    assert _close(s[col], ref[col][i])
